import { readFile, readdir, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
let source = path.resolve(root, "../printbench");
let check = false;
for (let i = 0; i < args.length; i++) {
  if (args[i] === "--check") check = true;
  else if (args[i] === "--source" && args[i + 1])
    source = path.resolve(args[++i]);
  else throw new Error(`Unknown or incomplete argument: ${args[i]}`);
}

// Compute every output before writing anything: missing source sections must fail safely.
const outputs = new Map();
const banner =
  "<!-- Generated by npm run docs:sync from PrintBench/printbench. Edit the source, not this file. -->\n\n";
const contribute = await readFile(path.join(source, "CONTRIBUTING.md"), "utf8");
function section(title) {
  const heading = `## ${title}\n`;
  const start = contribute.indexOf(heading);
  if (start < 0) throw new Error(`Missing CONTRIBUTING.md section: ${title}`);
  const body = contribute.slice(start + heading.length);
  const end = body.search(/^## /m);
  return (end < 0 ? body : body.slice(0, end)).trim() + "\n";
}
for (const [name, title] of [
  ["setup", "Getting set up"],
  ["testing", "Running the checks"],
  ["invariants", "Things worth knowing before you change them"],
  ["commits", "Commits and pull requests"],
]) {
  outputs.set(`docs/.vitepress/shared/${name}.md`, banner + section(title));
}
const security = await readFile(path.join(source, "SECURITY.md"), "utf8");
outputs.set(
  "docs/.vitepress/shared/security.md",
  banner +
    security
      .replace(/^# .*\n\n/, "")
      .replaceAll("](docs/deployment.md)", "](/deploy/index)"),
);
outputs.set(
  "docs/contributing/releasing.md",
  banner + (await readFile(path.join(source, "docs/releasing.md"), "utf8")),
);

const releases = (await readdir(path.join(source, "docs/releases")))
  .filter((name) => /^v\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?\.md$/.test(name))
  .sort((a, b) => {
    const core = (name) => name.slice(0, -3).split("-")[0];
    if (core(a) === core(b) && a.includes("-") !== b.includes("-"))
      return a.includes("-") ? 1 : -1;
    return b.localeCompare(a, "en", { numeric: true });
  });
if (!releases.length) throw new Error("No authored release notes found");
const items = [];
for (const file of releases) {
  const tag = file.slice(0, -3);
  outputs.set(
    `docs/releases/${file}`,
    banner +
      (
        await readFile(path.join(source, "docs/releases", file), "utf8")
      ).replaceAll("](../model-imports.md)", "](/guide/imports)"),
  );
  items.push({ text: tag, link: `/releases/${tag}` });
}
outputs.set(
  "docs/.vitepress/releases.json",
  JSON.stringify(items, null, 2) + "\n",
);
outputs.set(
  "docs/releases/index.md",
  banner +
    "# Release Notes\n\nAuthored notes from the app repository. Each page describes changes and upgrade steps.\n\n" +
    items.map(({ text, link }) => `- [${text}](${link})`).join("\n") +
    "\n\nSee [Upgrading](/deploy/upgrading) for the deployment procedure.\n",
);

const stale = [];
for (const [file, content] of outputs) {
  const destination = path.join(root, file);
  let existing;
  try {
    existing = await readFile(destination, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (existing === content) continue;
  stale.push(file);
  if (!check) {
    await mkdir(path.dirname(destination), { recursive: true });
    await writeFile(destination, content);
  }
}
if (check && stale.length) {
  console.error(
    `Shared documentation is stale:\n${stale.join("\n")}\nRun npm run docs:sync -- --source <app-checkout>, then commit the generated files.`,
  );
  process.exitCode = 1;
} else
  console.log(
    check
      ? "Shared documentation matches the app source."
      : `Updated ${stale.length} generated files.`,
  );
